-- 0004_history_state.sql -- telemetry_state, the change-only history of
-- non-number values.
--
-- Source of truth: mybo-at-v2 docs/19-stack-replan-2026-10.md § 5.1 (the
-- "same shape" docs/04 promised for text, bool and json and never built). The
-- deliberate additions are marked below.
--
-- A row is a CHANGE, not a sample. The edge sends a changed string, bool or
-- object once, plus its heartbeat, so "the state at t" is the last row at or
-- before t and "what happened" is the rows in a range. There are no rollups:
-- an average of "shore" and "inverter" means nothing.
--
-- A bool is stored as value_text 'true' or 'false' and the series row's
-- value_kind says which kind the text is; any other non-number value that is
-- not a string is stored whole in value_json. Exactly one of the two is set.
--
-- APPLIED MIGRATIONS ARE IMMUTABLE. Add 000N+1; do not edit this file.

CREATE TABLE IF NOT EXISTS telemetry_state (
  ts                TIMESTAMPTZ NOT NULL,
  vessel_id         UUID NOT NULL,
  series_id         BIGINT NOT NULL,
  installation_role SMALLINT NOT NULL DEFAULT 0,
  value_text        TEXT,
  value_json        JSONB,
  -- ADDITION (docs/19 states it as a comment): the rule is enforced, so a
  -- writer bug that sets both or neither fails the batch instead of storing a
  -- row no read can interpret. JSON null is the jsonb value 'null', which is
  -- not SQL NULL, so a SignalK value that went null is still storable.
  CONSTRAINT telemetry_state_one_value CHECK ((value_text IS NULL) <> (value_json IS NULL)),
  -- The natural key, as telemetry_numeric's: the consumer is at-least-once,
  -- so a redelivered batch must insert nothing (ON CONFLICT DO NOTHING).
  UNIQUE (vessel_id, series_id, ts, installation_role)
);

COMMENT ON COLUMN telemetry_state.installation_role IS '0 primary, 1 shadow';

-- 7-day chunks (docs/19 § 5.1): non-number paths change rarely, so a 1-day
-- chunk would be mostly empty chunks.
SELECT create_hypertable(
  'telemetry_state',
  by_range('ts', INTERVAL '7 days'),
  if_not_exists => TRUE
);

-- Columnstore after 3 days, segmentby as telemetry_numeric (0001 explains why
-- installation_role is in it: it is in the UNIQUE key).
ALTER TABLE telemetry_state SET (
  timescaledb.enable_columnstore = true,
  timescaledb.segmentby = 'vessel_id, series_id, installation_role',
  timescaledb.orderby   = 'ts DESC'
);

CALL add_columnstore_policy('telemetry_state', after => INTERVAL '3 days', if_not_exists => TRUE);

-- The read index is the UNIQUE constraint: "state at t" is a backward scan of
-- (vessel_id, series_id, ts) that stops at the first row, and "transitions in
-- a range" is a forward range scan of the same prefix.
