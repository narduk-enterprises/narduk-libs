-- narduk:no-transaction
--
-- 0008_rollups_exclude_import_overlay.sql -- rows tagged `quality = 3` stay in
-- raw and never reach a rollup (mybo-at-v2 D-152, #280).
--
-- WHAT quality = 3 MEANS. `telemetry_numeric.quality` is SMALLINT NOT NULL
-- DEFAULT 0. The writer's values are 0 good or unmarked, 1 stale, 2 suspect;
-- 3 is import provenance: a row a history import carried that duplicates
-- what another import already holds for the same minute -- production
-- Tideye's 30 s import overlay, whose `:30` rows sit beside the 1-minute
-- import's `:00` rows. Counting both makes every 1m bucket over those minutes
-- a mean of the minute with its second half counted twice. The rows are kept
-- (Logan, D-152: "keep and tag"); only the rollups stop counting them. Stale
-- and suspect rows (1, 2) stay in every rollup exactly as before, and the
-- column cannot be NULL, so `quality <> 3` is the whole predicate.
--
-- WHY A DROP. A continuous aggregate's query cannot be altered, so the ladder
-- is dropped coarsest first (each level reads the one below) and recreated
-- from 0002's four definitions unchanged except the 1m level's filter, which
-- every coarser level inherits. 0002's comments hold for every level here.
-- `IF NOT EXISTS` stays on each CREATE so a re-run after a partial failure
-- still converges; the DROPs make the CREATEs real on a first run.
--
-- WHAT THE DROP COSTS. A dropped CAgg loses its materialized buckets, and the
-- views are recreated `WITH NO DATA`. The scheduled policies rebuild the last
-- 7 days (1m, 15m, 1h) and 30 days (1d); every older bucket stays empty until
-- an `ops` refresh rebuilds it from raw, bottom-up, with
-- `refreshRollupsStatements({ range })` (README, "Backfill older than the
-- refresh window"). A rollup bucket is rebuildable only while raw still holds
-- its minutes, so a deployment that sweeps raw (`globalRawWindowMs` a number)
-- loses rollup history older than its raw window when this runs. The
-- deployment this was written for keeps raw forever (mybo-at-v2 D-140,
-- `globalRawWindowMs: 'never'`).
--
-- A DROP ALSO LOSES THE GRANTS, so 0003's SELECT grants on the four views are
-- re-issued below, line for line as `historyRoleGrantStatements()` emits them
-- (tests/migrations.test.ts asserts it). 0007 grants nothing on these views.
--
-- The directive on line 1 is load-bearing for the same reason as 0002's:
-- `CREATE MATERIALIZED VIEW ... WITH (timescaledb.continuous)` cannot run
-- inside a transaction block, so the runner sends one statement per round
-- trip. The file is therefore not atomic: a failure part-way leaves some
-- levels dropped, and re-running it finishes the job.
--
-- APPLIED MIGRATIONS ARE IMMUTABLE. Add 000N+1; do not edit this file.

DROP MATERIALIZED VIEW IF EXISTS telemetry_numeric_1d;
DROP MATERIALIZED VIEW IF EXISTS telemetry_numeric_1h;
DROP MATERIALIZED VIEW IF EXISTS telemetry_numeric_15m;
DROP MATERIALIZED VIEW IF EXISTS telemetry_numeric_1m;

-- 0002's four views, unchanged but for the 1m filter.
CREATE MATERIALIZED VIEW IF NOT EXISTS telemetry_numeric_1m
WITH (timescaledb.continuous, timescaledb.materialized_only = true) AS
  SELECT
    time_bucket(INTERVAL '1 minute', ts) AS bucket,
    vessel_id,
    series_id,
    count(*)         AS n,
    sum(value)       AS sum_value,
    min(value)       AS min_value,
    max(value)       AS max_value,
    last(value, ts)  AS last_value
  FROM telemetry_numeric
  WHERE installation_role = 0 AND quality <> 3
  GROUP BY 1, 2, 3
WITH NO DATA;

CREATE MATERIALIZED VIEW IF NOT EXISTS telemetry_numeric_15m
WITH (timescaledb.continuous, timescaledb.materialized_only = true) AS
  SELECT
    time_bucket(INTERVAL '15 minutes', bucket) AS bucket,
    vessel_id,
    series_id,
    sum(n)                    AS n,
    sum(sum_value)            AS sum_value,
    min(min_value)            AS min_value,
    max(max_value)            AS max_value,
    last(last_value, bucket)  AS last_value
  FROM telemetry_numeric_1m
  GROUP BY 1, 2, 3
WITH NO DATA;

CREATE MATERIALIZED VIEW IF NOT EXISTS telemetry_numeric_1h
WITH (timescaledb.continuous, timescaledb.materialized_only = true) AS
  SELECT
    time_bucket(INTERVAL '1 hour', bucket) AS bucket,
    vessel_id,
    series_id,
    sum(n)                    AS n,
    sum(sum_value)            AS sum_value,
    min(min_value)            AS min_value,
    max(max_value)            AS max_value,
    last(last_value, bucket)  AS last_value
  FROM telemetry_numeric_15m
  GROUP BY 1, 2, 3
WITH NO DATA;

CREATE MATERIALIZED VIEW IF NOT EXISTS telemetry_numeric_1d
WITH (timescaledb.continuous, timescaledb.materialized_only = true) AS
  SELECT
    time_bucket(INTERVAL '1 day', bucket) AS bucket,
    vessel_id,
    series_id,
    sum(n)                    AS n,
    sum(sum_value)            AS sum_value,
    min(min_value)            AS min_value,
    max(max_value)            AS max_value,
    last(last_value, bucket)  AS last_value
  FROM telemetry_numeric_1h
  GROUP BY 1, 2, 3
WITH NO DATA;

