-- 0005_history_time_weighted.sql -- time-weighted rollups for change-only
-- numeric series (owed since mybo-at-v2 D-127; docs/19 § 3 and § 10 L3).
--
-- WHY A SECOND ROLLUP. The 0002 ladder averages SAMPLES: sum(value) / n. That
-- is right for a fixed-rate stream and wrong for a change-only one, which is
-- what the edge's reducer sends: a value is written when it changes, plus a
-- heartbeat, and it HOLDS until the next row. A minute that read 10 for 50 s
-- and 20 for 10 s has two rows and a sample mean of 15; the boat's value over
-- that minute was (10 * 50 + 20 * 10) / 60 = 11.67. This table carries the
-- integral instead, so the mean is weighted by how long each value held.
--
-- WHY NOT A CONTINUOUS AGGREGATE. The integral needs each row's NEXT row (how
-- long it held), and the head of every bucket needs the PREVIOUS bucket's last
-- value (what was held when the bucket opened). Both cross rows or buckets,
-- and a continuous aggregate allows neither a window function nor a look at
-- another bucket. So this is a plain hypertable that the library refreshes
-- with bounded statements (`refreshTimeWeightedStatements` in
-- src/timescale/time-weighted.ts): the 1-minute rows from raw with lead(), and
-- the 15m, 1h and 1d rows summed from the 1-minute rows. Summing is exact at
-- every level because each 1-minute row is the integral over exactly that
-- minute -- held time is split at the bucket boundary, never attributed whole
-- to the bucket a row started in.
--
-- A gap longer than the refresh's `maxHoldMs` is no data, not a held value:
-- held_seconds is the covered time, and the mean is weighted_sum /
-- held_seconds over that covered time only.
--
-- Primary installation only (installation_role = 0), as 0002's ladder: a mean
-- of two instruments is not the vessel's value.
--
-- OPT-IN. Nothing refreshes this table until a consumer runs the refresh, and
-- 0002's rollups are untouched; a consumer that never refreshes has an empty
-- table and nothing else changes.
--
-- APPLIED MIGRATIONS ARE IMMUTABLE. Add 000N+1; do not edit this file.

CREATE TABLE IF NOT EXISTS telemetry_numeric_tw (
  -- 60, 900, 3600 or 86400: the level, as its width. One table for the
  -- ladder, so one refresh statement can write the three coarse levels.
  bucket_seconds INTEGER NOT NULL CHECK (bucket_seconds IN (60, 900, 3600, 86400)),
  bucket         TIMESTAMPTZ NOT NULL,
  vessel_id      UUID NOT NULL,
  series_id      BIGINT NOT NULL,
  -- Raw rows that STARTED in this bucket. 0 for a minute whose whole value
  -- was held from an earlier row.
  n              BIGINT NOT NULL,
  -- Seconds of the bucket a value covered. At most the bucket width.
  held_seconds   DOUBLE PRECISION NOT NULL,
  -- sum(value * seconds held inside this bucket). Mean = weighted_sum /
  -- held_seconds.
  weighted_sum   DOUBLE PRECISION NOT NULL,
  -- Extremes and last of the values HELD in the bucket, including a value
  -- carried in from an earlier bucket.
  min_value      DOUBLE PRECISION,
  max_value      DOUBLE PRECISION,
  last_value     DOUBLE PRECISION,
  UNIQUE (vessel_id, series_id, bucket_seconds, bucket)
);

-- 30-day chunks: about 1,560 rows per series per day across the four levels.
SELECT create_hypertable(
  'telemetry_numeric_tw',
  by_range('bucket', INTERVAL '30 days'),
  if_not_exists => TRUE
);

