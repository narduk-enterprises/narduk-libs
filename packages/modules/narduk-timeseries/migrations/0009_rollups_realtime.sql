-- 0009_rollups_realtime.sql -- rollup reads reach the present (mybo-at-v2#533).
--
-- THE PROBLEM. 0002 and 0008 state `timescaledb.materialized_only = true` on
-- all four levels and give each level an `end_offset` and `schedule_interval`
-- of its own bucket width. On the 1m -> 15m -> 1h -> 1d chain that made a 1h
-- bucket readable two to three hours after it opened and a 1d bucket about two
-- days after: a 24 h chart never showed its last two or three hours, a 30 d
-- chart never showed its last two days, and a vessel claimed less than about
-- two and a half hours ago read as having no history at all, although raw and
-- the 1m level held every point.
--
-- THE FIX, TWO PARTS.
--
-- 1. Real-time aggregation on 15m, 1h and 1d (`materialized_only = false`).
--    A read of one of these views is its materialized rows below the
--    watermark plus, above it, the same aggregate computed at read time from
--    the level below -- the 1h tail from the 15m view, whose own tail comes
--    from 1m. The read stays bounded: each tail spans at most one
--    `end_offset` plus one `schedule_interval` of the level below, and the
--    caller's `vessel_id` / `series_id` / `bucket` predicates are on the
--    views' GROUP BY columns, so they reach the tail's scan. The newest
--    bucket is therefore partial while it is still being written: its `n` and
--    `sum_value` grow until the hour or day closes. 1m stays
--    `materialized_only = true`: its lag is about two minutes, and keeping it
--    materialized keeps raw out of every rollup read.
--
-- 2. Tighter 1h and 1d policies. 1h: `end_offset` 15 minutes on a 15-minute
--    schedule (was 1 hour / 1 hour), so an hour is materialized about 15 to
--    30 minutes after it closes. 1d: `end_offset` 1 hour (was 1 day), so a
--    UTC day is materialized within about two hours of closing. A 1h refresh
--    that runs before the 15m level has materialized the hour's last quarter
--    is corrected by the next run: refreshing a lower level of a hierarchical
--    aggregate logs an invalidation on the level above, and every policy
--    still reconsiders its full 7-day (30-day at 1d) window. 1m and 15m keep
--    0002's policies.
--
-- WHAT IT DOES NOT DO. No view is dropped or recreated, so no materialized
-- bucket and no grant is lost (contrast 0008). Each step is reversible:
-- `materialized_only = true` and 0002's policy arguments restore the old
-- behaviour. Policies are replaced with `remove_continuous_aggregate_policy`
-- then `add_continuous_aggregate_policy`, because the add's `if_not_exists`
-- leaves an existing policy's arguments untouched.
--
-- APPLIED MIGRATIONS ARE IMMUTABLE. Add 000N+1; do not edit this file.

ALTER MATERIALIZED VIEW telemetry_numeric_15m SET (timescaledb.materialized_only = false);
ALTER MATERIALIZED VIEW telemetry_numeric_1h SET (timescaledb.materialized_only = false);
ALTER MATERIALIZED VIEW telemetry_numeric_1d SET (timescaledb.materialized_only = false);

SELECT remove_continuous_aggregate_policy('telemetry_numeric_1h', if_exists => TRUE);
SELECT add_continuous_aggregate_policy('telemetry_numeric_1h',
  start_offset => INTERVAL '7 days',
  end_offset   => INTERVAL '15 minutes',
  schedule_interval => INTERVAL '15 minutes',
  if_not_exists => TRUE);

SELECT remove_continuous_aggregate_policy('telemetry_numeric_1d', if_exists => TRUE);
SELECT add_continuous_aggregate_policy('telemetry_numeric_1d',
  start_offset => INTERVAL '30 days',
  end_offset   => INTERVAL '1 hour',
  schedule_interval => INTERVAL '1 hour',
  if_not_exists => TRUE);
