-- 0006_history_ais.sql -- AIS contacts and encounters.
--
-- Source of truth: mybo-at-v2 docs/19-stack-replan-2026-10.md § 4.3 (D-141).
-- The 400-odd raw AIS streams a busy harbour carries NEVER reach this store:
-- every reduced report stays in the product's batch journal, and only what an
-- encounter builder derives from them lands here. That is how "never into
-- Timescale" and "keep everything" both hold.
--
-- These are plain tables, not hypertables: a boat has a few hundred contacts
-- and a handful of encounters a day, which is no time-series volume.
--
-- "Around me now" (docs/19 § 4.4, `ais_now`) is not here on purpose: it is
-- one D1 row per vessel in the product, upserted at most every 5 minutes, and
-- the history store has no part in it.
--
-- `vessel_id` is always the OBSERVING vessel -- the boat whose edge heard the
-- target -- never the target. A target is its MMSI. Two of our boats hearing
-- the same ship are two contacts.
--
-- APPLIED MIGRATIONS ARE IMMUTABLE. Add 000N+1; do not edit this file.

-- One row per (observing vessel, target). Latest static data only: static
-- data arrives on change, and its history is in the journal.
CREATE TABLE IF NOT EXISTS ais_contact (
  vessel_id    UUID NOT NULL,
  -- 9 digits; fits INTEGER (999,999,999 < 2^31).
  mmsi         INTEGER NOT NULL CHECK (mmsi > 0 AND mmsi <= 999999999),
  first_seen   TIMESTAMPTZ NOT NULL,
  last_seen    TIMESTAMPTZ NOT NULL,
  name         TEXT,
  call_sign    TEXT,
  imo          INTEGER,
  ship_type    SMALLINT,
  length_m     REAL,
  beam_m       REAL,
  destination  TEXT,
  -- Static fields this schema does not name, as the edge sent them.
  static_extra JSONB,
  static_updated_at TIMESTAMPTZ,
  PRIMARY KEY (vessel_id, mmsi),
  CHECK (last_seen >= first_seen)
);

-- A closed encounter: the target came inside the watch radius, and its
-- closest approach was near enough to keep. The track is the target's,
-- trimmed around the closest approach, with time as the M coordinate (epoch
-- seconds), so a chart can play it back against the vessel's own track.
CREATE TABLE IF NOT EXISTS ais_encounter (
  vessel_id      UUID NOT NULL,
  mmsi           INTEGER NOT NULL CHECK (mmsi > 0 AND mmsi <= 999999999),
  start_ts       TIMESTAMPTZ NOT NULL,
  end_ts         TIMESTAMPTZ NOT NULL,
  cpa_distance_m DOUBLE PRECISION NOT NULL CHECK (cpa_distance_m >= 0),
  cpa_ts         TIMESTAMPTZ NOT NULL,
  track          GEOGRAPHY(LINESTRINGM, 4326),
  -- Set by the product's passage builder by time overlap; null at anchor or
  -- in a marina. TEXT: the passage id is the product's, not this store's.
  passage_id     TEXT,
  -- The natural key: an encounter rebuilt from the same journal day lands
  -- on the same row (repair is a replay, docs/19 § 4.3).
  PRIMARY KEY (vessel_id, mmsi, start_ts),
  CHECK (end_ts >= start_ts),
  CHECK (cpa_ts >= start_ts AND cpa_ts <= end_ts)
);

-- "Encounters on this day" and "encounters of this passage".
CREATE INDEX IF NOT EXISTS ais_encounter_vessel_start_idx ON ais_encounter (vessel_id, start_ts);
CREATE INDEX IF NOT EXISTS ais_encounter_passage_idx ON ais_encounter (vessel_id, passage_id)
  WHERE passage_id IS NOT NULL;

-- The working table: one row per target currently inside the watch radius.
-- Small by construction (at most the targets in range), extended per batch,
-- and deleted when the encounter closes -- it holds no captured change, only
-- the builder's progress, which a replay of the journal rebuilds.
CREATE TABLE IF NOT EXISTS ais_encounter_open (
  vessel_id      UUID NOT NULL,
  mmsi           INTEGER NOT NULL CHECK (mmsi > 0 AND mmsi <= 999999999),
  start_ts       TIMESTAMPTZ NOT NULL,
  -- The last report inside the radius; the builder closes the row after its
  -- silence or out-of-range timeout.
  last_seen      TIMESTAMPTZ NOT NULL,
  cpa_distance_m DOUBLE PRECISION NOT NULL CHECK (cpa_distance_m >= 0),
  cpa_ts         TIMESTAMPTZ NOT NULL,
  track          GEOGRAPHY(LINESTRINGM, 4326),
  passage_id     TEXT,
  PRIMARY KEY (vessel_id, mmsi),
  CHECK (last_seen >= start_ts)
);
